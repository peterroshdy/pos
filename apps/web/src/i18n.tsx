type MessageKey = keyof typeof messages.en;
type I18nValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey) => string;
  tr: (english: string, arabic: string) => string;
};
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<Language>(
    () => (localStorage.getItem("token-taste-language") as Language) || "en",
  );
  const setLanguage = (next: Language) => {
    localStorage.setItem("token-taste-language", next);
    setLanguageState(next);
  };
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    return localizeDocument(language);
  }, [language]);
  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (key: MessageKey) => messages[language][key],
      tr: (english: string, arabic: string) =>
        language === "ar" ? arabic : english,
    }),
    [language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}
